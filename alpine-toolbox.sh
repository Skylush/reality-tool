#!/bin/sh

set -u

if [ "$(id -u)" -ne 0 ]; then
    echo "请使用 root 执行此工具箱"
    exit 1
fi

DNS_BACKUP="/etc/resolv.conf.bak"
SSH_KEY='ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIBDQZBjnnhbfwtFhrPlCUXur64RAgdJzcJCP1l2tWWtE Generated By Termius'
SSH_DIR="/root/.ssh"
AUTHORIZED_KEYS="$SSH_DIR/authorized_keys"

install_base() {
    echo
    echo "[*] 更新 Alpine 软件源..."
    apk update || exit 1

    echo "[*] 安装基础组件..."
    apk add --no-cache curl wget ca-certificates || exit 1

    echo "[OK] 基础组件安装完成"
}

configure_dns() {
    echo
    echo "[*] 配置 IPv6 DNS..."

    if [ ! -e "$DNS_BACKUP" ]; then
        cp /etc/resolv.conf "$DNS_BACKUP"
        echo "[OK] 已备份原 DNS: $DNS_BACKUP"
    fi

    printf '%s\n' \
    'nameserver 2a00:1098:2b::1' \
    'nameserver 2a01:4f9:c010:3f02::1' \
    'nameserver 2a01:4f8:c2c:123f::1' \
    'nameserver 2a00:1098:2c::1' \
    > /etc/resolv.conf

    echo "[OK] 当前 DNS:"
    cat /etc/resolv.conf
}

set_sshd_option() {
    key="$1"
    value="$2"

    if grep -Eq "^[#[:space:]]*$key[[:space:]]" /etc/ssh/sshd_config; then
        sed -i -E "s|^[#[:space:]]*$key[[:space:]].*|$key $value|" /etc/ssh/sshd_config
    else
        printf '%s %s\n' "$key" "$value" >> /etc/ssh/sshd_config
    fi
}

install_ssh_key() {
    echo
    echo "[*] 配置 SSH 密钥登录..."

    mkdir -p "$SSH_DIR"
    chmod 700 "$SSH_DIR"

    touch "$AUTHORIZED_KEYS"

    if ! grep -Fqx "$SSH_KEY" "$AUTHORIZED_KEYS"; then
        printf '%s\n' "$SSH_KEY" >> "$AUTHORIZED_KEYS"
    fi

    chmod 600 "$AUTHORIZED_KEYS"
    chown -R root:root "$SSH_DIR"

    if command -v sshd >/dev/null 2>&1; then
        echo "[*] 检测到 OpenSSH"

        cp -a /etc/ssh/sshd_config \
            "/etc/ssh/sshd_config.bak.$(date +%Y%m%d%H%M%S)"

        set_sshd_option PasswordAuthentication no
        set_sshd_option KbdInteractiveAuthentication no
        set_sshd_option PubkeyAuthentication yes
        set_sshd_option AuthorizedKeysFile .ssh/authorized_keys
        set_sshd_option PermitRootLogin prohibit-password

        echo "[*] 检查 SSH 配置..."
        sshd -t || {
            echo "[ERROR] SSH 配置检查失败，未重启服务"
            exit 1
        }

        rc-update add sshd default >/dev/null 2>&1 || true
        rc-service sshd restart

        echo "[OK] OpenSSH 密钥登录配置完成"
        echo "[提示] 请先用新终端测试密钥登录，再关闭当前 SSH 连接"

    elif command -v dropbear >/dev/null 2>&1; then
        echo "[*] 检测到 Dropbear"

        if [ ! -f /etc/conf.d/dropbear ]; then
            touch /etc/conf.d/dropbear
        fi

        cp -a /etc/conf.d/dropbear \
            "/etc/conf.d/dropbear.bak.$(date +%Y%m%d%H%M%S)"

        if grep -q '^DROPBEAR_OPTS=' /etc/conf.d/dropbear; then
            sed -i -E 's|^DROPBEAR_OPTS=.*|DROPBEAR_OPTS="-s"|' /etc/conf.d/dropbear
        else
            printf '%s\n' 'DROPBEAR_OPTS="-s"' >> /etc/conf.d/dropbear
        fi

        rc-update add dropbear default >/dev/null 2>&1 || true
        rc-service dropbear restart

        echo "[OK] Dropbear 密钥登录配置完成"
        echo "[说明] Dropbear 的 -s 参数表示禁止密码登录"
    else
        echo "[*] 未检测到 SSH 服务，安装 OpenSSH..."

        apk add --no-cache openssh-server || exit 1

        rc-update add sshd default
        rc-service sshd start

        cp -a /etc/ssh/sshd_config \
            "/etc/ssh/sshd_config.bak.$(date +%Y%m%d%H%M%S)"

        set_sshd_option PasswordAuthentication no
        set_sshd_option KbdInteractiveAuthentication no
        set_sshd_option PubkeyAuthentication yes
        set_sshd_option AuthorizedKeysFile .ssh/authorized_keys
        set_sshd_option PermitRootLogin prohibit-password

        sshd -t
        rc-service sshd restart

        echo "[OK] OpenSSH 安装并配置完成"
    fi
}

install_komari() {
    echo
    echo "[*] 安装 Komari Agent"

    stty sane </dev/tty
    printf '请输入新的 Agent Token: '
    stty -echo </dev/tty
    IFS= read -r KOMARI_TOKEN </dev/tty
    stty echo </dev/tty
    printf '\n'

    curl -6 -fsSL \
        https://raw.githubusercontent.com/komari-monitor/komari-agent/refs/heads/main/install.sh \
    | sed 's/[[:space:]]curl / curl -6 /g' \
    | sh -s -- \
        --install-version 1.2.13 \
        --install-service-name komari-agent \
        --install-no-mirror \
        -e 'https://komari.ysoo.de' \
        -t "$KOMARI_TOKEN" \
        --disable-auto-update \
        --month-rotate 1

    unset KOMARI_TOKEN

    echo
    rc-service komari-agent status
}

show_menu() {
    echo
    echo "======================================"
    echo " Alpine IPv6 VPS 多功能工具箱"
    echo "======================================"
    echo "1. 配置 SSH 密钥登录"
    echo "2. 安装 Komari Agent"
    echo "3. 配置 SSH 密钥 + 安装 Komari"
    echo "0. 退出"
    echo "======================================"
    printf "请选择: "
}

install_base
configure_dns

while true; do
    show_menu
    read -r choice

    case "$choice" in
        1)
            install_ssh_key
            ;;
        2)
            install_komari
            ;;
        3)
            install_ssh_key
            install_komari
            ;;
        0)
            echo "已退出"
            exit 0
            ;;
        *)
            echo "无效选项，请重新选择"
            ;;
    esac
done
