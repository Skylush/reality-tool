#!/bin/sh
set -eu

KEY='ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIBDQZBjnnhbfwtFhrPlCUXur64RAgdJzcJCP1l2tWWtE Generated By Termius'
SSH_DIR="/root/.ssh"
AUTHORIZED_KEYS="$SSH_DIR/authorized_keys"
SSHD_CONFIG="/etc/ssh/sshd_config"

mkdir -p "$SSH_DIR"
chmod 700 "$SSH_DIR"

touch "$AUTHORIZED_KEYS"
grep -Fqx "$KEY" "$AUTHORIZED_KEYS" || printf '%s\n' "$KEY" >> "$AUTHORIZED_KEYS"
chmod 600 "$AUTHORIZED_KEYS"
chown -R root:root "$SSH_DIR"

cp -a "$SSHD_CONFIG" "$SSHD_CONFIG.bak.$(date +%Y%m%d%H%M%S)"

set_option() {
    key="$1"
    value="$2"

    if grep -Eq "^[#[:space:]]*$key[[:space:]]" "$SSHD_CONFIG"; then
        sed -i -E "s|^[#[:space:]]*$key[[:space:]].*|$key $value|" "$SSHD_CONFIG"
    else
        printf '%s %s\n' "$key" "$value" >> "$SSHD_CONFIG"
    fi
}

set_option PasswordAuthentication no
set_option KbdInteractiveAuthentication no
set_option PubkeyAuthentication yes
set_option AuthorizedKeysFile .ssh/authorized_keys
set_option PermitRootLogin prohibit-password

sshd -t
rc-update add sshd default >/dev/null 2>&1 || true
rc-service sshd restart

echo "SSH 密钥登录配置完成"
echo "请使用新终端测试密钥登录成功后，再关闭当前连接"
